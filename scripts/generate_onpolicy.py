"""Generate on-policy THINKING-mode responses with the base model (data for Orthrus).

`scripts/build_orthrus_corpus.py` copies Nemotron responses verbatim (written by other
models): off-policy. The paper (Appendix A) distils on outputs generated by the frozen AR
head itself. This script keeps only the prompt (system + first user turn) of each row,
generates the reply with the base model in thinking mode via vLLM and writes a JSONL
with the exact generated token ids:

    python scripts/generate_onpolicy.py --in data/orthrus-sft.jsonl \
        --out data/orthrus-onpolicy-think.jsonl --model Qwen/Qwen3-0.6B

Then: scripts/build_packed_cache_ids.py (exact tokens, keeps truncated traces as
prefixes, supervises the whole <think>...answer span, conversation-aligned rows).
`messages` is also written for inspection and for the legacy text packer.

Sampling defaults are Qwen3's thinking-mode recommendation (T=0.6, top_p=0.95, top_k=20).
Qwen advises against greedy decoding in thinking mode (repetition loops).
"""

from __future__ import annotations

import argparse
import json
import sys

from transformers import AutoTokenizer


def parse_args():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--in", dest="inp", required=True, help="messages JSONL (prompts).")
    p.add_argument("--out", required=True, help="Output JSONL.")
    p.add_argument("--model", default="Qwen/Qwen3-0.6B",
                   help="Base model: must be the one the Orthrus init copies.")
    p.add_argument("--temperature", type=float, default=0.6)
    p.add_argument("--top-p", type=float, default=0.95)
    p.add_argument("--top-k", type=int, default=20)
    p.add_argument("--max-tokens", type=int, default=3584,
                   help="Reasoning traces beyond this are kept as prefixes (still "
                        "on-policy) unless --drop-truncated.")
    p.add_argument("--max-model-len", type=int, default=4096,
                   help="prompt budget = max-model-len - max-tokens; longer prompts are "
                        "skipped. Match --seq-len of the packer.")
    p.add_argument("--drop-truncated", action="store_true",
                   help="Drop responses cut by --max-tokens. Required only for the legacy "
                        "text packer (the chat template cannot render an unclosed <think>).")
    p.add_argument("--min-distinct-ngram", type=float, default=0.3,
                   help="Drop responses whose distinct-8-gram ratio is below this "
                        "(cheap repetition-loop filter). 0 disables.")
    p.add_argument("--batch", type=int, default=8192, help="Prompts per vLLM call.")
    p.add_argument("--limit", type=int, default=None)
    p.add_argument("--gpu-memory-utilization", type=float, default=0.9)
    p.add_argument("--seed", type=int, default=42)
    return p.parse_args()


def prompt_messages(messages: list) -> list | None:
    """System (optional) + first user turn. Everything after is discarded."""
    out = []
    for m in messages:
        role = m.get("role")
        if role == "system" and not out:
            out.append({"role": "system", "content": m["content"]})
        elif role == "user":
            out.append({"role": "user", "content": m["content"]})
            return out
        else:
            break
    return None


def distinct_ngram_ratio(text: str, n: int = 8) -> float:
    toks = text.split()
    if len(toks) < 4 * n:
        return 1.0
    grams = [tuple(toks[i:i + n]) for i in range(len(toks) - n + 1)]
    return len(set(grams)) / len(grams)


def main():
    args = parse_args()
    from vllm import LLM, SamplingParams

    tokenizer = AutoTokenizer.from_pretrained(args.model)
    stop_ids = {tokenizer.convert_tokens_to_ids("<|im_end|>"), tokenizer.eos_token_id}
    prompt_budget = args.max_model_len - args.max_tokens

    rows, prompt_ids = [], []
    skipped_long = 0
    with open(args.inp) as f:
        for line in f:
            msgs = prompt_messages(json.loads(line).get("messages", []))
            if msgs is None:
                continue
            # Exact prompt tokens; the same template call the eval harness makes.
            ids = tokenizer.apply_chat_template(
                msgs, tokenize=True, return_dict=True, add_generation_prompt=True,
                enable_thinking=True,
            )["input_ids"]
            if len(ids) > prompt_budget:
                skipped_long += 1
                continue
            rows.append(msgs)
            prompt_ids.append(list(ids))
            if args.limit and len(rows) >= args.limit:
                break
    print(f"prompts: {len(rows):,} (skipped {skipped_long:,} longer than "
          f"{prompt_budget} tokens)", file=sys.stderr)

    llm = LLM(model=args.model, dtype="bfloat16", max_model_len=args.max_model_len,
              gpu_memory_utilization=args.gpu_memory_utilization,
              enable_prefix_caching=True, seed=args.seed)
    sp = SamplingParams(temperature=args.temperature, top_p=args.top_p,
                        top_k=args.top_k, max_tokens=args.max_tokens, seed=args.seed)

    kept = dropped_trunc = dropped_rep = n_trunc = 0
    with open(args.out, "w") as out:
        for start in range(0, len(rows), args.batch):
            batch_ids = prompt_ids[start:start + args.batch]
            outs = llm.generate([{"prompt_token_ids": ids} for ids in batch_ids], sp)
            for msgs, ids, o in zip(rows[start:start + args.batch], batch_ids, outs):
                c = o.outputs[0]
                text = c.text.strip()
                if not text:
                    continue
                finished = c.finish_reason == "stop"
                if not finished:
                    n_trunc += 1
                    if args.drop_truncated:
                        dropped_trunc += 1
                        continue
                if args.min_distinct_ngram > 0 and \
                        distinct_ngram_ratio(text) < args.min_distinct_ngram:
                    dropped_rep += 1
                    continue
                resp = [int(t) for t in c.token_ids]
                while resp and resp[-1] in stop_ids:  # the packer re-adds <|im_end|>
                    resp.pop()
                out.write(json.dumps({
                    "messages": msgs + [{"role": "assistant", "content": text}],
                    "prompt_ids": ids,
                    "response_ids": resp,
                    "finished": finished,
                }, ensure_ascii=False) + "\n")
                kept += 1
            print(f"{min(start + args.batch, len(rows)):,}/{len(rows):,} kept={kept:,} "
                  f"truncated={n_trunc:,} (dropped {dropped_trunc:,}) "
                  f"repetitive={dropped_rep:,}", file=sys.stderr)

    print(f"wrote {kept:,} on-policy samples to {args.out}\n"
          f"Next:\n  python scripts/build_packed_cache_ids.py --dataset-path {args.out} "
          f"--out data/processed/orthrus-onpolicy-{args.max_model_len} "
          f"--model-dir pretrained-models/orthrus-qwen3-0.6b-init "
          f"--seq-len {args.max_model_len}")


if __name__ == "__main__":
    main()
